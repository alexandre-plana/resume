import { memo, useEffect, useRef, useState } from 'react'
import { useAppStore } from '../store/appStore'
import styles from './Toolbar.module.css'
import { getTranslations } from '../locales'

interface ToolbarProps {
  language: 'fr' | 'en'
}

function ToolbarComponent({ language }: ToolbarProps) {
  const setLanguage = useAppStore((state) => state.setLanguage)
  const t = getTranslations(language)
  const [isHidden, setIsHidden] = useState(false)
  const lastScrollY = useRef(0)

  useEffect(() => {
    lastScrollY.current = window.scrollY

    const handleScroll = () => {
      const currentScrollY = window.scrollY
      const isScrollingDown = currentScrollY > lastScrollY.current
      const delta = Math.abs(currentScrollY - lastScrollY.current)

      if (currentScrollY <= 8) {
        setIsHidden(false)
      } else if (delta > 4 && isScrollingDown) {
        setIsHidden(true)
      } else if (delta > 4 && !isScrollingDown) {
        setIsHidden(false)
      }

      lastScrollY.current = currentScrollY
    }

    window.addEventListener('scroll', handleScroll, { passive: true })

    return () => {
      window.removeEventListener('scroll', handleScroll)
    }
  }, [])

  // The one-page A4 CV is generated by `npm run export:pdf` and served as a static file.
  const pdfUrl = `${import.meta.env.BASE_URL}pdf/cv-alexandre-plana-${language}.pdf`

  const handlePrint = () => {
    const frame = document.createElement('iframe')
    frame.style.cssText = 'position:fixed;width:0;height:0;border:0;visibility:hidden'
    frame.src = pdfUrl
    frame.onload = () => {
      try {
        frame.contentWindow?.focus()
        frame.contentWindow?.print()
      } catch {
        window.open(pdfUrl, '_blank', 'noopener')
      }
      setTimeout(() => frame.remove(), 60_000)
    }
    document.body.appendChild(frame)
  }

  const printLabel = t.toolbar.print
  const exportPdfLabel = t.toolbar.exportPdf

  return (
    <div className={`${styles.toolbar} ${isHidden ? styles.toolbarHidden : ''}`}>
      <div className={styles.actions}>
        <div className={styles.langControl}>
          <button
            className={`${styles.langBtn} ${language === 'fr' ? styles.active : ''}`}
            type="button"
            aria-pressed={language === 'fr'}
            onClick={() => setLanguage('fr')}
            title="Français"
          >
            FR
          </button>
          <button
            className={`${styles.langBtn} ${language === 'en' ? styles.active : ''}`}
            type="button"
            aria-pressed={language === 'en'}
            onClick={() => setLanguage('en')}
            title="English"
          >
            EN
          </button>
        </div>
        <a className={styles.exportBtn} href={pdfUrl} download title={exportPdfLabel}>
          <span className={styles.icon}>📄</span>
          {exportPdfLabel}
        </a>
        <button className={styles.printBtn} onClick={handlePrint} title={printLabel}>
          <span className={styles.icon}>🖨️</span>
          {printLabel}
        </button>
      </div>
    </div>
  )
}

export const Toolbar = memo(ToolbarComponent)
